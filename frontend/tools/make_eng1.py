"""Activities for Stemford English 1 (Class 1): picture games from the book's own "match the words with
their pictures" exercises, and write-and-colour pages. No AI stories.

Run from the repository root (the QR Watch-this videos are already in books/library.js):
    PYTHONPATH=tools python tools/make_eng1.py
As in Maths 1, Science 1 and Social Studies 1: every lesson page can be written on and coloured in.
Games: page 11 (duck, family, teeth, basket), page 22 (hen, red, net, peg), page 97 (the animals printed
with their names) and page 106 (tiger, elephant, parrot, hare, monkey). The output adds to the book's
earlier activities in books/activities.js (the page 5-7 read-along of the printed story "The Picnic").
"""
import json
import make_maths4 as m4
from make_sst1 import make_game, write_keeping_endings

BOOK = 'stemford-english-1'
ROOT = m4.ROOT
FIRST_PAGE = 4          # pages 1-3: title page and contents

# Pictures of the printed exercises (positions in % of the page, measured on each page).
GAMES = {
    11: ('Match the words with their pictures', [('teeth', 68.5, 14.4, 6.9, 7.4), ('duck', 68.5, 23.6, 10, 7.7),
                                                 ('basket', 68.7, 33.4, 9.4, 7.4), ('family', 68.1, 41.9, 10.7, 10.6)]),
    22: ('Match the words with their pictures', [('net', 46, 32.8, 9.4, 5.4), ('peg', 47.7, 40, 5.8, 6.7),
                                                 ('hen', 46.9, 47.9, 7.3, 6.8), ('red', 47.1, 56.6, 8, 5.3)]),
    97: ('Find the animal', [('cow', 18.3, 63.7, 14.6, 10.1), ('dog', 42.7, 63.7, 14.2, 10), ('cat', 69, 65.1, 11.4, 8.2),
                             ('lion', 14.6, 74.9, 17.3, 11.1), ('monkey', 43.8, 76.1, 10, 10.2), ('deer', 70, 74.9, 9.6, 11)]),
    106: ('Match the pictures with their names', [('monkey', 12.3, 76.5, 8.3, 7.4), ('tiger', 25.9, 79, 17.3, 5), ('elephant', 48.5, 76.3, 12.8, 7.5),
                                                  ('parrot', 66.5, 76.8, 6.4, 7.3), ('hare', 79.6, 76.5, 5.9, 7.5)]),
}


def main():
    m4.BOOK = BOOK          # reuse the blank-paper button placement on this book's pages
    meta = json.loads((ROOT / f'books/{BOOK}/meta.json').read_text(encoding='utf-8'))
    palette_path = ROOT / 'books/colour-palettes.json'
    palette = json.loads(palette_path.read_text(encoding='utf-8'))
    names = ['black', 'red', 'blue', 'green', 'yellow', 'orange', 'pink', 'brown', 'purple']
    palette['books'][BOOK] = {str(p): {'picture': 'Writing: black pencil; pictures: free colours', 'colours': ['black'] if p < FIRST_PAGE else names}
                              for p in range(1, meta['pages'] + 1)}
    write_keeping_endings(palette_path, json.dumps(palette, ensure_ascii=False, indent=2) + '\n')
    acts = {}
    for page in range(FIRST_PAGE, meta['pages'] + 1):
        entries = []
        taken = m4.qr_taken(page)   # the QR code and its Watch-this button
        if page in GAMES:
            h, w = m4.cv2.imread(str(ROOT / f'books/{BOOK}/p{page:03}.jpg')).shape[:2]
            taken += [(int(x / 100 * w), int(y / 100 * h), int(bw / 100 * w), int(bh / 100 * h)) for _, x, y, bw, bh in GAMES[page][1]]
            entries.append(make_game(page, *GAMES[page], taken))
        entries.append({'type': 'fill', 'title': 'Write and colour', 'colours': [palette['colours'][c] for c in names],
                        'steps': [{'say': 'Do the exercise on this page. Write your answers and colour the pictures.', 'marks': []}]})
        acts[page] = entries
    source = '// Generated by tools/make_eng1.py: games and write-and-colour pages, no AI stories.\n'
    source += '// Added after the earlier English 1 activities of books/activities.js (kept on their pages).\n'
    source += "window.BOOK_ACTIVITIES = window.BOOK_ACTIVITIES || {};\n(() => {\n"
    source += f"  const id = '{BOOK}', earlier = window.BOOK_ACTIVITIES[id] || {{}};\n"
    source += '  const added = ' + json.dumps(acts, ensure_ascii=False, indent=1).replace('\n', '\n  ') + ';\n'
    source += '  for (const page of Object.keys(added)) added[page] = [].concat(earlier[page] || [], added[page]);\n'
    source += '  window.BOOK_ACTIVITIES[id] = { ...earlier, ...added };\n})();\n'
    (ROOT / 'books/activities-eng1.js').write_text(source, encoding='utf-8')
    print(f'English 1: {len(acts)} pages, {sum(len(v) for v in acts.values())} activities, {len(GAMES)} games.')


if __name__ == '__main__':
    main()
