"""Activities for Stemford Islamiat 1 (Class 1, Urdu): a tap-the-picture game and write-and-colour pages. No AI stories.

Run from the repository root after import_isl1.py and link_isl1_videos.py (the QR Watch-this videos):
    PYTHONPATH=tools python tools/make_isl1.py
As in Urdu 1: every lesson page can be written on and coloured in. Page 17 prints the five senses as
pictures to match with their words (دیکھنا، سننا ...): it becomes a "تصویر پہچانیں" game.
"""
import json
import make_maths4 as m4
import make_urdu1 as u1

BOOK = 'stemford-islamiat-1'
ROOT = m4.ROOT
FIRST_PAGE = 5          # pages 1-4: title page, syllabus plan and contents

# Pictures printed for "match the words with their pictures" (positions in % of the page, measured on the page).
GAMES = {
    17: ('تصویر پہچانیں', [('دیکھنا', 11.2, 43.2, 14, 10.2), ('چکھنا', 37.2, 49.1, 14, 10.2), ('سننا', 11.2, 55.1, 14, 10.2),
                           ('سونگھنا', 37.2, 60.9, 14, 10.2), ('چھونا', 11.2, 66.8, 14, 10.3)]),
}


def main():
    m4.BOOK = BOOK          # reuse the blank-paper button placement on this book's pages
    meta = json.loads((ROOT / f'books/{BOOK}/meta.json').read_text(encoding='utf-8'))
    palette_path = ROOT / 'books/colour-palettes.json'
    palette = json.loads(palette_path.read_text(encoding='utf-8'))
    names = ['black', 'red', 'blue', 'green', 'yellow', 'orange', 'pink', 'brown', 'purple']
    palette['books'][BOOK] = {str(p): {'picture': 'Writing: black pencil; pictures: free colours', 'colours': ['black'] if p < FIRST_PAGE else names}
                              for p in range(1, meta['pages'] + 1)}
    u1.write_keeping_endings(palette_path, json.dumps(palette, ensure_ascii=False, indent=2) + '\n')
    acts = {}
    for page in range(FIRST_PAGE, meta['pages'] + 1):
        entries = []
        taken = m4.qr_taken(page)   # the QR code and its Watch-this button
        if page in GAMES:
            h, w = m4.cv2.imread(str(ROOT / f'books/{BOOK}/p{page:03}.jpg')).shape[:2]
            taken += [(int(x / 100 * w), int(y / 100 * h), int(bw / 100 * w), int(bh / 100 * h)) for _, x, y, bw, bh in GAMES[page][1]]
            entries.append(u1.make_game(page, *GAMES[page], taken))
        entries.append({'type': 'fill', 'title': 'لکھیں اور رنگ بھریں', 'colours': [palette['colours'][c] for c in names],
                        'steps': [{'say': 'اس صفحے کی مشق کریں۔ لکھیں اور تصویروں میں رنگ بھریں۔', 'marks': []}]})
        acts[page] = entries
    source = '// Generated by tools/make_isl1.py: a game and write-and-colour pages, no AI stories.\n'
    source += f"window.BOOK_ACTIVITIES = window.BOOK_ACTIVITIES || {{}};\nwindow.BOOK_ACTIVITIES['{BOOK}'] = " + json.dumps(acts, ensure_ascii=False, indent=1) + ';\n'
    (ROOT / 'books/activities-isl1.js').write_text(source, encoding='utf-8')
    print(f'Islamiat 1: {len(acts)} pages, {sum(len(v) for v in acts.values())} activities, {len(GAMES)} games.')


if __name__ == '__main__':
    main()
