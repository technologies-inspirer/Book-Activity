"""Activities for Stemford Maths 1 (Class 1): picture games from the book's own named pictures and
matching exercise, and write-and-colour pages. No AI stories.

Run from the repository root after import_maths1.py and link_maths1_videos.py (the QR Watch-this videos):
    PYTHONPATH=tools python tools/make_maths1.py
As in Science 1 and Social Studies 1: every lesson page can be written on and coloured in. Games:
  page 26  - Exercise 1.2 "Count the objects ... match them with their number words": hear a number word, tap its group
  page 93  - the Pakistani coins and notes printed with their names: hear a coin or note, tap it
  page 117 - the basic shapes printed with their names: hear a shape, tap it
"""
import json
import make_maths4 as m4
from make_sst1 import write_keeping_endings

BOOK = 'stemford-maths-1'
ROOT = m4.ROOT
FIRST_PAGE = 3          # pages 1-2: title page and contents

ROWS = [('thirteen', 16.5, 21.9), ('seventeen', 23.5, 29.2), ('twenty', 30.8, 35.8), ('fourteen', 37.3, 43.8), ('eighteen', 45.8, 51.5),
        ('nineteen', 53.1, 60.4), ('twelve', 62.7, 71.2), ('sixteen', 73.5, 78.5), ('fifteen', 80.4, 86.5), ('eleven', 88.3, 95.2)]
# (name shown, x, y, w, h, words spoken) in % of the page, measured on each page
GAMES = {
    26: ('Count and find the number', [(n, 7, y0, 43.5, round(y1 - y0, 1), n + '.') for n, y0, y1 in ROWS]),
    93: ('Find the coin or note', [('Re. 1 coin', 11.9, 58.9, 8.5, 5.5, 'one rupee coin.'), ('Rs. 2 coin', 32.9, 58.9, 9.4, 5.5, 'two rupee coin.'),
                                   ('Rs. 5 coin', 54.6, 58.8, 9.1, 5.8, 'five rupee coin.'), ('Rs. 10 coin', 76.3, 58.4, 10.6, 6.7, 'ten rupee coin.'),
                                   ('Rs. 10 note', 19.6, 72.5, 24, 9.7, 'ten rupee note.'), ('Rs. 20 note', 64, 72.3, 25.6, 10, 'twenty rupee note.'),
                                   ('Rs. 50 note', 17.3, 84.7, 26.3, 9.3, 'fifty rupee note.'), ('Rs. 100 note', 62.2, 84.7, 27.6, 9.3, 'hundred rupee note.')]),
    117: ('Find the shape', [('Circle', 11.4, 52.7, 11.5, 8.4, 'circle.'), ('Square', 29.7, 52.7, 11.5, 8.4, 'square.'),
                             ('Triangle', 48, 52.7, 17.1, 8.4, 'triangle.'), ('Rectangle', 71.9, 53, 16.8, 7.8, 'rectangle.')]),
}


# Game button placed by eye where the blank-paper search lands on the text under the shapes (page 117).
BUTTON_AT = {117: {'x': 76, 'y': 47.5}}


def make_game(page, title, cells, taken):
    targets = [{'name': n, 'x': x, 'y': y, 'w': w, 'h': h, 'say': say} for n, x, y, w, h, say in cells]
    x0, y0 = max(0, min(t['x'] for t in targets) - 1), max(0, min(t['y'] for t in targets) - 1)
    x1, y1 = min(100, max(t['x'] + t['w'] for t in targets) + 1), min(100, max(t['y'] + t['h'] for t in targets) + 1)
    crop = {'x': round(x0, 1), 'y': round(y0, 1), 'w': round(x1 - x0, 1), 'h': round(y1 - y0, 1)}
    return {'type': 'game', 'title': title, 'button': BUTTON_AT.get(page) or m4.clear_spot(page, [crop[k] for k in 'xywh'], taken), 'crop': crop, 'targets': targets}


def main():
    m4.BOOK = BOOK          # reuse the blank-paper button placement on this book's pages
    meta = json.loads((ROOT / f'books/{BOOK}/meta.json').read_text(encoding='utf-8'))
    palette_path = ROOT / 'books/colour-palettes.json'
    palette = json.loads(palette_path.read_text(encoding='utf-8'))
    names = ['black', 'red', 'blue', 'green', 'yellow', 'orange', 'pink', 'brown', 'purple']
    palette['books'][BOOK] = {str(p): {'picture': 'Writing: black pencil; pictures: free colours', 'colours': ['black'] if p < FIRST_PAGE else names}
                              for p in range(1, meta['pages'] + 1)}
    write_keeping_endings(palette_path, json.dumps(palette, ensure_ascii=False, indent=2) + '\n')
    acts = {}
    for page in range(FIRST_PAGE, meta['pages'] + 1):
        entries = []
        taken = m4.qr_taken(page)   # the QR code and its Watch-this button
        if page in GAMES:
            h, w = m4.cv2.imread(str(ROOT / f'books/{BOOK}/p{page:03}.jpg')).shape[:2]
            taken += [(int(x / 100 * w), int(y / 100 * h), int(bw / 100 * w), int(bh / 100 * h)) for _, x, y, bw, bh, _ in GAMES[page][1]]
            entries.append(make_game(page, *GAMES[page], taken))
        entries.append({'type': 'fill', 'title': 'Write and colour', 'colours': [palette['colours'][c] for c in names],
                        'steps': [{'say': 'Do the exercise on this page. Write your answers and colour the pictures.', 'marks': []}]})
        acts[page] = entries
    source = '// Generated by tools/make_maths1.py: games and write-and-colour pages, no AI stories.\n'
    source += f"window.BOOK_ACTIVITIES = window.BOOK_ACTIVITIES || {{}};\nwindow.BOOK_ACTIVITIES['{BOOK}'] = " + json.dumps(acts, ensure_ascii=False, indent=1) + ';\n'
    (ROOT / 'books/activities-maths1.js').write_text(source, encoding='utf-8')
    print(f'Maths 1: {len(acts)} pages, {sum(len(v) for v in acts.values())} activities, {len(GAMES)} games.')


if __name__ == '__main__':
    main()
