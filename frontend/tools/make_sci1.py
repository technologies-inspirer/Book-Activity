"""Activities for Stemford Science 1 (Class 1): the printed picture-match exercises as games and
write-and-colour pages. No AI stories.

Run from the repository root after link_sci1_videos.py (the QR Watch-this videos):
    PYTHONPATH=tools python tools/make_sci1.py
As in Social Studies 1: every lesson page can be written on and coloured in. The book's own picture-match
exercises (pages 38, 47, 67) become "find the picture" games: the child hears a name and taps its picture.
"""
import json
import make_maths4 as m4
from make_sst1 import make_game, write_keeping_endings

BOOK = 'stemford-science-1'
ROOT = m4.ROOT
FIRST_PAGE = 4          # pages 1-3: title page, "What's Inside" and contents

# Pictures of the printed match exercises (positions in % of the page, measured on each page).
GAMES = {
    38: ('Match the plant parts', [('leaf', 6, 10.8, 14, 5.9), ('roots', 33, 11.1, 8.5, 6.9),
                                   ('flower', 58.5, 10.6, 8.8, 6.4), ('stem', 82, 11, 10.3, 6.9)]),
    47: ('Match the animals', [('water animal', 7.5, 64.8, 9.6, 5.1), ('pet', 5.5, 75.9, 13, 8.3), ('insect', 6.5, 86.3, 12, 6.7),
                               ('domestic animal', 75, 62.6, 18, 12.6), ('wild animal', 73.7, 83.2, 20, 9.5)]),
    67: ('Match the uses of water', [('Cooking food', 77.7, 8.1, 14, 10.1), ('Brushing teeth', 70.6, 18.6, 14, 10.1),
                                     ('Washing clothes', 77.7, 29.2, 14, 10), ('Drinking', 70.6, 39.6, 14, 10),
                                     ('Mopping', 77.7, 50.1, 14, 9.9)]),
}


def main():
    m4.BOOK = BOOK          # reuse the blank-paper button placement on this book's pages
    meta = json.loads((ROOT / f'books/{BOOK}/meta.json').read_text(encoding='utf-8'))
    palette_path = ROOT / 'books/colour-palettes.json'
    palette = json.loads(palette_path.read_text(encoding='utf-8'))
    names = ['black', 'red', 'blue', 'green', 'yellow', 'orange', 'pink', 'brown', 'purple']
    palette['books'][BOOK] = {str(p): {'picture': 'Writing: black pencil; pictures: free colours', 'colours': ['black'] if p < FIRST_PAGE else names}
                              for p in range(1, meta['pages'] + 1)}
    write_keeping_endings(palette_path, json.dumps(palette, ensure_ascii=False, indent=2) + '\n')
    acts = {}
    for page in range(FIRST_PAGE, meta['pages'] + 1):
        entries = []
        taken = m4.qr_taken(page)   # the QR code and its Watch-this button
        if page in GAMES:
            h, w = m4.cv2.imread(str(ROOT / f'books/{BOOK}/p{page:03}.jpg')).shape[:2]
            taken += [(int(x / 100 * w), int(y / 100 * h), int(bw / 100 * w), int(bh / 100 * h)) for _, x, y, bw, bh in GAMES[page][1]]
            entries.append(make_game(page, *GAMES[page], taken))
        entries.append({'type': 'fill', 'title': 'Write and colour', 'colours': [palette['colours'][c] for c in names],
                        'steps': [{'say': 'Do the exercise on this page. Write your answers and colour the pictures.', 'marks': []}]})
        acts[page] = entries
    source = '// Generated by tools/make_sci1.py: games and write-and-colour pages, no AI stories.\n'
    source += f"window.BOOK_ACTIVITIES = window.BOOK_ACTIVITIES || {{}};\nwindow.BOOK_ACTIVITIES['{BOOK}'] = " + json.dumps(acts, ensure_ascii=False, indent=1) + ';\n'
    (ROOT / 'books/activities-sci1.js').write_text(source, encoding='utf-8')
    print(f'Science 1: {len(acts)} pages, {sum(len(v) for v in acts.values())} activities, {len(GAMES)} games.')


if __name__ == '__main__':
    main()
