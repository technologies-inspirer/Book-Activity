"""Activities for Stemford Social Studies 2 (Class 2): the printed "identify the flags" exercise as a game and
write-and-colour pages. No AI stories.

Run from the repository root after import_sst2.py and link_sst2_videos.py (the QR Watch-this videos):
    PYTHONPATH=tools python tools/make_sst2.py
As in Social Studies 1: every lesson page can be written on and coloured in. Page 18 asks to identify six flags
(printed with their names on page 16): it becomes a "find the flag" game.
"""
import json
import make_maths4 as m4

BOOK = 'stemford-social-studies-2'
m4.BOOK = BOOK          # reuse the blank-paper button placement on this book's pages
ROOT = m4.ROOT
FIRST_PAGE = 4          # pages 1-3: title page, "What's Inside" and contents

# The flags of page 18 (positions in % of the page, measured on the page); their names are printed on page 16.
GAMES = {
    18: ('Find the flag', [('Saudi Arabia', 17.2, 9.2, 26.1, 13.1), ('Iran', 57, 9.2, 26.2, 13.1), ('Afghanistan', 17.2, 28.3, 26.1, 13),
                           ('China', 57, 28.3, 26.2, 13), ('Turkey', 17.2, 47.2, 26.1, 13.1), ('Bangladesh', 57, 47.2, 26.2, 13.1)]),
}


def make_game(page, title, cells, taken):
    targets = [{'name': n, 'x': x, 'y': y, 'w': w, 'h': h, 'say': n if n.endswith('.') else n + '.'} for n, x, y, w, h in cells]
    x0, y0 = max(0, min(t['x'] for t in targets) - 1), max(0, min(t['y'] for t in targets) - 1)
    x1, y1 = min(100, max(t['x'] + t['w'] for t in targets) + 1), min(100, max(t['y'] + t['h'] for t in targets) + 1)
    crop = {'x': round(x0, 1), 'y': round(y0, 1), 'w': round(x1 - x0, 1), 'h': round(y1 - y0, 1)}
    return {'type': 'game', 'title': title, 'button': m4.clear_spot(page, [crop[k] for k in 'xywh'], taken), 'crop': crop, 'targets': targets}


def write_keeping_endings(path, text):
    crlf = b'\r\n' in path.read_bytes() if path.exists() else False
    path.write_bytes((text.replace('\r\n', '\n').replace('\n', '\r\n') if crlf else text).encode('utf-8'))


def main():
    meta = json.loads((ROOT / f'books/{BOOK}/meta.json').read_text(encoding='utf-8'))
    palette_path = ROOT / 'books/colour-palettes.json'
    palette = json.loads(palette_path.read_text(encoding='utf-8'))
    names = ['black', 'red', 'blue', 'green', 'yellow', 'orange', 'pink', 'brown', 'purple']
    palette['books'][BOOK] = {str(p): {'picture': 'Writing: black pencil; pictures: free colours', 'colours': ['black'] if p < FIRST_PAGE else names}
                              for p in range(1, meta['pages'] + 1)}
    write_keeping_endings(palette_path, json.dumps(palette, ensure_ascii=False, indent=2) + '\n')
    acts = {}
    for page in range(FIRST_PAGE, meta['pages'] + 1):
        entries = []
        taken = m4.qr_taken(page)   # the QR code and its Watch-this button
        if page in GAMES:
            h, w = m4.cv2.imread(str(ROOT / f'books/{BOOK}/p{page:03}.jpg')).shape[:2]
            taken += [(int(x / 100 * w), int(y / 100 * h), int(bw / 100 * w), int(bh / 100 * h)) for _, x, y, bw, bh in GAMES[page][1]]
            entries.append(make_game(page, *GAMES[page], taken))
        entries.append({'type': 'fill', 'title': 'Write and colour', 'colours': [palette['colours'][c] for c in names],
                        'steps': [{'say': 'Do the exercise on this page. Write your answers and colour the pictures.', 'marks': []}]})
        acts[page] = entries
    source = '// Generated by tools/make_sst2.py: games and write-and-colour pages, no AI stories.\n'
    source += f"window.BOOK_ACTIVITIES = window.BOOK_ACTIVITIES || {{}};\nwindow.BOOK_ACTIVITIES['{BOOK}'] = " + json.dumps(acts, ensure_ascii=False, indent=1) + ';\n'
    (ROOT / 'books/activities-sst2.js').write_text(source, encoding='utf-8')
    print(f'Social Studies 2: {len(acts)} pages, {sum(len(v) for v in acts.values())} activities, {len(GAMES)} games.')


if __name__ == '__main__':
    main()
