"""Find the printed checklists of the practice pages and write books/checklists.js.

A checklist is two columns of small white answer boxes on a yellow panel (Yes / No, or جی ہاں / جی نہیں), one
row per statement, and in the Urdu books a row of five stars for the teacher's rating under them. The reader
turns each into a question the child (or teacher) ticks (app.js openQuestion, kind 'tick').

Run from the repository root:  python tools/find_checklists.py
"""
import json
from pathlib import Path
import cv2
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
BOOKS = {'new-stemford-english-3': False, 'stemford-urdu-3': True, 'stemford-urdu-4': True, 'stemford-english-4': False,
         'stemford-maths-3': False, 'stemford-maths-4': False, 'stemford-series-computer-book-0-curve': False}

def white_parts(im, y_from):
    """White components (boxes, stars) below y_from (% of the page): [x, y, w, h] in % of the page."""
    h, w = im.shape[:2]
    white = (im.min(axis=2) > 236).astype(np.uint8)
    white[:int(y_from / 100 * h)] = 0
    n, _, stats, _ = cv2.connectedComponentsWithStats(white, connectivity=4)
    return [[x / w * 100, y / h * 100, bw / w * 100, bh / h * 100] for x, y, bw, bh, _ in stats[1:]]

def yellowish(im, r):
    """True when the ring round a box is the checklist's yellow panel."""
    h, w = im.shape[:2]
    x0, y0, x1, y1 = [int(v) for v in (r[0] / 100 * w - 6, r[1] / 100 * h - 6, (r[0] + r[2]) / 100 * w + 6, (r[1] + r[3]) / 100 * h + 6)]
    ring = im[max(0, y0):y1, max(0, x0):x1].reshape(-1, 3).astype(int)
    b, g, rr = ring[:, 0], ring[:, 1], ring[:, 2]
    return ((rr > 220) & (g > 190) & (b < 200)).mean() > .25

def find(book, page, urdu):
    im = cv2.imread(str(ROOT / f'books/{book}/p{page:03}.jpg'))
    if im is None:
        return None
    parts = white_parts(im, 60)
    boxes = [r for r in parts if 3.5 < r[2] < 11 and 1.6 < r[3] < 4.5 and yellowish(im, r)]
    if len(boxes) < 8:
        return None
    # two columns of boxes, rows paired by height
    xs = sorted({round(b[0]) for b in boxes})
    cols = []
    for b in sorted(boxes, key=lambda b: b[0]):
        for c in cols:
            if abs(c[0][0] - b[0]) < 2.5:
                c.append(b); break
        else:
            cols.append([b])
    cols = [sorted(c, key=lambda b: b[1]) for c in cols if len(c) >= 4]
    if len(cols) != 2:
        return None
    left, right = sorted(cols, key=lambda c: c[0][0])
    rows = []
    for a in left:
        b = min(right, key=lambda b: abs(b[1] - a[1]))
        if abs(b[1] - a[1]) < 1.2:
            rows.append((a, b))
    if len(rows) < 4:
        return None
    # Yes / No: English has Yes then No left to right; Urdu has جی نہیں (no) left of جی ہاں (yes)
    yes_no = [{'yes': [round(v, 2) for v in (b if urdu else a)], 'no': [round(v, 2) for v in (a if urdu else b)]} for a, b in rows]
    bottom = max(r[1] + r[3] for r in left + right)
    stars = []
    if urdu:
        stars = sorted([r for r in parts if 1.5 < r[2] < 4 and 1.2 < r[3] < 3.5 and bottom < r[1] < bottom + 6 and r[0] < 45],
                       key=lambda r: r[0])[:5]
        stars = [[round(v, 2) for v in s] for s in stars] if len(stars) == 5 else []
    top = min(r[1] for r in left + right)
    end = (max(s[1] + s[3] for s in stars) if stars else bottom) + 1.5
    return {'rows': yes_no, 'stars': stars, 'crop': [3, round(top - 5, 2), 94, round(end - top + 5, 2)]}

def main():
    out, count = {}, 0
    for book, urdu in BOOKS.items():
        meta = json.loads((ROOT / f'books/{book}/meta.json').read_text(encoding='utf-8')) if (ROOT / f'books/{book}/meta.json').exists() else None
        pages = meta['pages'] if meta else 100
        for page in range(1, pages + 1):
            found = find(book, page, urdu)
            if found:
                out.setdefault(book, {})[page] = found
                count += 1
    source = '// Generated by tools/find_checklists.py: the printed checklists of the practice pages.\n'
    source += 'window.BOOK_CHECKLISTS = ' + json.dumps(out, ensure_ascii=False, indent=1) + ';\n'
    (ROOT / 'books/checklists.js').write_text(source, encoding='utf-8')
    print(count, 'checklists:', {b: sorted(p) for b, p in out.items()})

if __name__ == '__main__':
    main()
