"""Turn PDF books into page images the reader can show.

    python tools/import_pdf.py "C:/path/Book One.pdf" "C:/path/Book Two.pdf"

For each PDF this writes books/<id>/p001.jpg ..., cover.jpg, text.json (the text
blocks of every page, used to pre-fill the voice text in Publisher mode) and
meta.json, then rebuilds books/library.js from every meta.json it finds.
"""
import glob
import json
import os
import re
import sys

import pymupdf

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'books')
PAGE_WIDTH = 1300       # px; sharp enough for a full-screen spread
COVER_WIDTH = 480


def clean_title(path):
    name = os.path.splitext(os.path.basename(path))[0]
    name = re.sub(r'\b(final|output|print|copy)\b', '', name, flags=re.I)
    return re.sub(r'\s+', ' ', name.replace('_', ' ')).strip()


def cover_colours(page):
    """Average colour of the cover, and a darker shade, for the spine and boards."""
    pix = page.get_pixmap(matrix=pymupdf.Matrix(0.05, 0.05), alpha=False)
    s = pix.samples
    n = len(s) // 3
    r, g, b = (sum(s[i::3]) // n for i in range(3))
    hexc = lambda k: '#%02x%02x%02x' % tuple(int(v * k) for v in (r, g, b))
    return hexc(0.85), hexc(0.5)


def import_pdf(path):
    title = clean_title(path)
    book_id = re.sub(r'[^a-z0-9]+', '-', title.lower()).strip('-')
    out = os.path.join(ROOT, book_id)
    os.makedirs(out, exist_ok=True)
    doc = pymupdf.open(path)
    first = doc[0].rect
    text = []
    for i, page in enumerate(doc):
        w, h = page.rect.width, page.rect.height
        zoom = PAGE_WIDTH / w
        page.get_pixmap(matrix=pymupdf.Matrix(zoom, zoom), alpha=False).save(
            os.path.join(out, 'p%03d.jpg' % (i + 1)), jpg_quality=82)
        blocks = []
        for x0, y0, x1, y1, txt, _no, kind in page.get_text('blocks'):
            txt = re.sub(r'\s+', ' ', txt).strip()
            if kind == 0 and txt:
                blocks.append([round(x0 / w * 100, 1), round(y0 / h * 100, 1),
                               round(x1 / w * 100, 1), round(y1 / h * 100, 1), txt])
        text.append(blocks)
        print('\r  %s: page %d/%d' % (title, i + 1, len(doc)), end='', flush=True)
    print()
    zoom = COVER_WIDTH / first.width
    doc[0].get_pixmap(matrix=pymupdf.Matrix(zoom, zoom), alpha=False).save(
        os.path.join(out, 'cover.jpg'), jpg_quality=85)
    c1, c2 = cover_colours(doc[0])
    with open(os.path.join(out, 'text.json'), 'w', encoding='utf-8') as f:
        json.dump(text, f, ensure_ascii=False)
    with open(os.path.join(out, 'meta.json'), 'w', encoding='utf-8') as f:
        json.dump({'id': book_id, 'title': title, 'dir': 'books/' + book_id, 'pages': len(doc),
                   'ratio': round(first.width / first.height, 4), 'c1': c1, 'c2': c2}, f, indent=2)


def rebuild_library():
    metas = []
    for m in sorted(glob.glob(os.path.join(ROOT, '*', 'meta.json'))):
        with open(m, encoding='utf-8') as f:
            metas.append(json.load(f))
    with open(os.path.join(ROOT, 'library.js'), 'w', encoding='utf-8') as f:
        f.write('// Generated by tools/import_pdf.py — do not edit by hand.\n')
        f.write('window.PDF_BOOKS = ' + json.dumps(metas, indent=2, ensure_ascii=False) + ';\n')
    print('library.js: %d book(s)' % len(metas))


if __name__ == '__main__':
    os.makedirs(ROOT, exist_ok=True)
    for pdf in sys.argv[1:]:
        import_pdf(pdf)
    rebuild_library()
