"""Record every Urdu sentence the Urdu book says, so it is spoken in Urdu on every phone.

Most phones (every iPhone, many Androids) have no Urdu voice, and the browser then reads Urdu with an English
voice. So each sentence is recorded once, with Microsoft's Pakistani Urdu voice, into books/<book>/audio/, and
books/audio-urdu3.js maps sentence -> file. The reader plays the recording when there is one.

    pip install edge-tts
    python tools/make_urdu_audio.py          # after make_urdu3.py; only new sentences are recorded
"""
import asyncio
import hashlib
import json
import os
import re

import edge_tts

BOOK = 'stemford-urdu-3'
VOICE = 'ur-PK-UzmaNeural'
OUT = 'books/%s/audio' % BOOK
URDU = re.compile('[؀-ۿ]')
# the reader speaks one sentence at a time, split the same way (app.js speak())
SENTENCES = re.compile(r'[^.!?۔؟]+[.!?۔؟]*\s*')


def sentences(text):
    return [s.strip() for s in SENTENCES.findall(text or '') if s.strip()]


def texts():
    src = open('books/activities-urdu3.js', encoding='utf-8').read()
    acts = json.loads(src[src.index('= ') + 2:src.rstrip().rindex(';')])
    said = []
    for page in acts.values():
        for a in page if isinstance(page, list) else [page]:
            if a['type'] == 'story':
                said += [sc['text'] for sc in a['scenes']]
                said.append('ختم شد۔')
            elif a['type'] == 'game':
                n = len(a['targets'])
                for t in a['targets']:
                    said += [f"{t['name']} کہاں ہے؟ اس پر ٹیپ کریں!", f"یہ {t['name']} ہے۔ دوبارہ کوشش کریں!",
                             f"شاباش! {t['say']}"]
                for stars in range(n + 1):
                    said.append(f'آپ نے {n} میں سے {stars} ستارے جیتے۔ بہت خوب!')
            elif a['type'] == 'fill':
                said += [st['say'] for st in a['steps']]
    out = []
    for t in said:
        for s in sentences(t):
            if URDU.search(s) and s not in out:
                out.append(s)
    return out


async def record(items):
    sem = asyncio.Semaphore(6)

    async def one(s, path):
        async with sem:
            for attempt in range(4):
                try:
                    await edge_tts.Communicate(s, VOICE, rate='-8%').save(path)
                    return
                except Exception as e:                   # the service sometimes drops a request: try again
                    if attempt == 3:
                        print('failed:', s, e)
                    await asyncio.sleep(2 * (attempt + 1))

    await asyncio.gather(*(one(s, p) for s, p in items))


if __name__ == '__main__':
    os.makedirs(OUT, exist_ok=True)
    found = texts()
    files = {s: '%s/%s.mp3' % (OUT, hashlib.md5(s.encode('utf-8')).hexdigest()[:12]) for s in found}
    todo = [(s, p) for s, p in files.items() if not os.path.exists(p) or os.path.getsize(p) == 0]
    print(len(found), 'sentences,', len(todo), 'to record')
    asyncio.run(record(todo))
    have = {s: p for s, p in files.items() if os.path.exists(p) and os.path.getsize(p) > 0}
    with open('books/audio-urdu3.js', 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/make_urdu_audio.py: recordings of the Urdu book\'s sentences.\n')
        f.write('window.RECORDED = Object.assign(window.RECORDED || {}, ')
        f.write(json.dumps(have, ensure_ascii=False, indent=0))
        f.write(');\n')
    print(len(have), 'recorded')
